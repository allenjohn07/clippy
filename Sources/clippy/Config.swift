import Cocoa

enum Config {
    /// How many rows the popup shows at once; the rest are reached by scrolling.
    static let popupVisibleRows = 9
    /// How many items the database keeps; older ones are deleted automatically.
    static let maxStoredItems = 1000
    /// Images are big, so they get their own, smaller cap.
    static let maxStoredImages = 100
    /// Larger images are not recorded.
    static let maxImageBytes = 25 * 1024 * 1024
    /// Longest side of the stored preview thumbnail, in pixels.
    static let thumbnailMaxPixels: CGFloat = 640
    static let popupWidth: CGFloat = 420
    static let rowHeight: CGFloat = 26
    static let footerHeight: CGFloat = 30
    /// Pasteboard polling. The tolerance lets macOS batch wake-ups with other work to save battery.
    static let pollInterval: TimeInterval = 0.5
    static let pollTolerance: TimeInterval = 0.2

    /// Tags our own synthesized key events so the event tap ignores them.
    static let eventMarker: Int64 = 0x434C4950

    /// Pasteboard types that mark sensitive/transient content we never record.
    static let ignoredPasteboardTypes: Set<String> = [
        "org.nspasteboard.ConcealedType",     // password managers
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword",
        "com.apple.is-sensitive",
        "de.petermaurer.TransientPasteboardType",
        "com.lastpass.LastPass",
    ]

    /// Copies made while one of these apps is in front are never recorded.
    static let passwordApps: Set<String> = [
        "com.apple.Passwords", "com.apple.keychainaccess",
        "com.agilebits.onepassword7", "com.1password.1password", "com.agilebits.onepassword-osx",
        "com.bitwarden.desktop", "com.lastpass.LastPass", "com.dashlane.Dashlane",
        "org.keepassxc.keepassxc", "in.sinew.Enpass-Desktop", "com.nordpass.macos.NordPass",
        "me.proton.pass.electron", "com.markmcguill.strongbox", "com.markmcguill.strongbox.mac",
    ]

    /// Pasteboard types that carry image data.
    static let imageTypes: [NSPasteboard.PasteboardType] = [
        .png, .tiff, NSPasteboard.PasteboardType("public.jpeg"), NSPasteboard.PasteboardType("public.heic"),
    ]

    /// Set CLIPPY_NO_NETWORK=1 to turn off YouTube thumbnail/title fetching.
    static var networkEnabled: Bool { ProcessInfo.processInfo.environment["CLIPPY_NO_NETWORK"] != "1" }

    static var databaseURL: URL {
        // Lets the end-to-end tests use a throwaway database instead of your real history.
        if let override = ProcessInfo.processInfo.environment["CLIPPY_DB_PATH"], !override.isEmpty {
            return URL(fileURLWithPath: override)
        }
        let base = FileManager.default.urls(for: .applicationSupportDirectory, in: .userDomainMask)[0]
        return base.appendingPathComponent("clippy", isDirectory: true)
                   .appendingPathComponent("history.db")
    }
}

enum KeyCode {
    static let v = 9
    static let down = 125
    static let up = 126
    static let returnKey = 36
    static let enter = 76
    static let escape = 53
    static let delete = 51
    /// Number-row keycodes for 1–9 → item index 0–8.
    static let digits: [Int: Int] = [18: 0, 19: 1, 20: 2, 21: 3, 23: 4, 22: 5, 26: 6, 28: 7, 25: 8]
}
